/*
 * Scans a pull request title + body for machine-attribution patterns that must
 * never enter public history — CLAUDE.md, "Never in public history".
 *
 * Plain Node, no build step: the workflow that calls this runs on the base ref
 * only (see pr-hygiene.yml) and must not need `npm ci` first, so this stays a
 * dependency-free .mjs the runner can execute directly.
 *
 * Exported separately from the CLI entry point below so the matching logic has
 * a unit test (tests/scripts/check-pr-hygiene.test.ts) independent of env vars
 * and process.exit.
 */

import { pathToFileURL } from 'node:url';

// Defined once and reused by every pattern that cares about *who* is being
// credited, so widening "who" (D4/D5/D6) never means touching more than one
// line.
const VENDORS = 'claude|anthropic|openai|gpt|copilot|codex|cursor|gemini|devin|aider';

const PATTERNS = [
  {
    kind: 'a machine co-author trailer',
    re: new RegExp(`co-authored-by:.*\\b(?:${VENDORS})\\b`, 'i'),
  },
  {
    // Covers "Generated with [Claude Code](...)" and "Generated by Claude"
    // alike: the bracket that wraps a linked tool name is optional, the verb
    // and the vendor are not.
    kind: 'a generated-with / created-by attribution',
    re: new RegExp(
      `\\b(?:generated|created|written|authored)\\s+(?:with|by)` + `\\s*\\[?\\s*(?:${VENDORS})\\b`,
      'i'
    ),
  },
  {
    // Two forms: the domain immediately followed by a known path segment
    // (chat/share/session/s, on either claude.ai or claude.com), and the
    // looser claude.ai/<anything containing session|chat|share> for paths
    // that don't put the keyword right after the domain. A `new RegExp`
    // string, not a `/.../ ` literal, so the two forms can be wrapped onto
    // separate lines instead of one line past the repo's print width.
    kind: 'an assistant session URL',
    re: new RegExp(
      '(?:claude\\.ai|claude\\.com)/(?:chat|share|session|s)/' +
        '|claude\\.ai/\\S*(?:session|chat|share)',
      'i'
    ),
  },
  {
    kind: 'a claude-session trailer',
    re: /^\s*claude-session:/i,
  },
  {
    // Reuses VENDORS rather than hardcoding anthropic.com, so a Devin/Cursor/
    // etc. noreply address is covered the same way without a second list.
    // Both `\S*` are bounded to `{0,64}` — an address is short, and an
    // unbounded `\S*` on both sides of the alternation is a polynomial
    // backtracking hotspot against a long non-matching run of non-whitespace.
    kind: 'an assistant noreply address',
    re: new RegExp(`noreply@\\S{0,64}(?:${VENDORS})\\S{0,64}`, 'i'),
  },
];

const normalize = (text) => (text ?? '').replace(/\r\n/g, '\n');

function scan(source, text, findings) {
  const lines = normalize(text).split('\n');
  for (let i = 0; i < lines.length; i++) {
    for (const { kind, re } of PATTERNS) {
      if (re.test(lines[i])) findings.push({ source, line: i + 1, kind });
    }
  }
}

/**
 * Returns every hit as `{ source: 'title' | 'body', line, kind }` — never the
 * matched text itself. `line` is 1-based within that source.
 */
export function findViolations(title, body) {
  const findings = [];
  scan('title', title, findings);
  scan('body', body, findings);
  return findings;
}

function main() {
  const findings = findViolations(process.env.PR_TITLE ?? '', process.env.PR_BODY ?? '');

  for (const { source, line, kind } of findings) {
    // Deliberately NEVER interpolate the matched substring into this line.
    // PR_TITLE/PR_BODY are attacker-controlled, and GitHub Actions reads a
    // `::error ...::<text>` line on stdout as a workflow command — echoing
    // the match would let a crafted title or body smuggle a second `::`
    // directive into the log. `kind` is one of the fixed strings above, and
    // `source`/`line` are a location, not content, so the whole message is
    // built only from values this script chose.
    console.log(
      `::error title=PR hygiene::Found ${kind} in the PR ${source}, line ${line}. ` +
        `Paraphrase instead of quoting it — see CONTRIBUTING.md or the pull request template.`
    );
  }

  if (findings.length > 0) {
    process.exitCode = 1;
  } else {
    console.log('No machine attribution in the title or body.');
  }
}

// Run when invoked directly by the workflow step, not when imported by the test.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
